import React, { useState } from 'react';
import { useNavigate, Link } from 'react-router-dom';
import { ShieldCheck, KeyRound, ArrowRight, Loader2, AlertCircle, Sun } from 'lucide-react';
import { useAuth } from '../context/AuthContext.js';

export const MfaChallengePage: React.FC = () => {
  const navigate = useNavigate();
  const { mfaChallenge, verifyMfaLogin, clearMfaChallenge } = useAuth();

  const [code, setCode] = useState('');
  const [isRecoveryMode, setIsRecoveryMode] = useState(false);
  const [isLoading, setIsLoading] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  // If no active challenge, redirect to login
  React.useEffect(() => {
    if (!mfaChallenge) {
      navigate('/login', { replace: true });
    }
  }, [mfaChallenge, navigate]);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setErrorMessage(null);
    setIsLoading(true);

    try {
      await verifyMfaLogin(code.trim(), isRecoveryMode);
      navigate('/', { replace: true });
    } catch (err: any) {
      setErrorMessage(err.message || 'MFA verification failed.');
    } finally {
      setIsLoading(false);
    }
  };

  const handleCancel = () => {
    clearMfaChallenge();
    navigate('/login');
  };

  return (
    <div className="min-h-screen w-full flex items-center justify-center p-4 sm:p-6 bg-slate-950 font-sans selection:bg-amber-500 selection:text-white relative overflow-hidden">
      {/* Background ambient glows */}
      <div className="absolute -top-32 -left-32 w-96 h-96 bg-amber-500/10 rounded-full blur-3xl pointer-events-none" />
      <div className="absolute bottom-0 right-0 w-80 h-80 bg-orange-600/10 rounded-full blur-3xl pointer-events-none" />

      <div className="w-full max-w-md bg-white dark:bg-slate-900 rounded-2xl border border-slate-200 dark:border-slate-800 shadow-2xl p-8 space-y-6 relative z-10">
        <div className="text-center space-y-3">
          <div className="w-14 h-14 rounded-2xl bg-amber-500/15 border border-amber-500/30 flex items-center justify-center text-amber-500 mx-auto shadow-lg shadow-amber-500/15">
            <ShieldCheck className="w-8 h-8" />
          </div>
          <div>
            <div className="flex items-center justify-center space-x-2 mb-1">
              <Sun className="w-4 h-4 text-amber-500" />
              <span className="text-xs font-bold text-slate-400 uppercase tracking-widest">
                INS SOLAR ERP
              </span>
            </div>
            <h2 className="text-2xl font-extrabold tracking-tight text-slate-900 dark:text-white">
              Two-Factor Authentication
            </h2>
            <p className="mt-1 text-xs text-slate-500 dark:text-slate-400">
              {isRecoveryMode
                ? 'Enter an unused 10-character emergency recovery code'
                : 'Enter the 6-digit code generated by your Authenticator app'}
            </p>
          </div>
        </div>

        {errorMessage && (
          <div className="p-3.5 rounded-xl bg-red-50 dark:bg-red-950/40 border border-red-200 dark:border-red-900/50 text-red-700 dark:text-red-300 text-xs flex items-start space-x-2">
            <AlertCircle className="w-4 h-4 shrink-0 mt-0.5 text-red-500" />
            <span>{errorMessage}</span>
          </div>
        )}

        <form onSubmit={handleSubmit} className="space-y-4">
          <div>
            <label className="block text-xs font-bold text-slate-700 dark:text-slate-300 uppercase tracking-wider mb-2">
              {isRecoveryMode ? '10-Character Recovery Code' : '6-Digit TOTP Code'}
            </label>
            <div className="relative">
              <div className="absolute inset-y-0 left-0 pl-3.5 flex items-center pointer-events-none text-slate-400">
                <KeyRound className="w-4 h-4" />
              </div>
              <input
                type="text"
                required
                maxLength={isRecoveryMode ? 10 : 6}
                value={code}
                onChange={e => setCode(e.target.value)}
                placeholder={isRecoveryMode ? 'XXXXXXXXXX' : '123456'}
                autoFocus
                className="w-full pl-10 pr-4 py-3 text-base font-mono tracking-[0.3em] text-center bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-xl focus:outline-none focus:ring-2 focus:ring-amber-500 text-slate-900 dark:text-white"
              />
            </div>
          </div>

          <button
            type="submit"
            disabled={isLoading || !code}
            className="w-full flex items-center justify-center space-x-2 py-3 px-4 rounded-xl bg-gradient-to-r from-amber-500 to-amber-600 hover:from-amber-600 hover:to-amber-700 text-slate-950 font-bold text-sm transition-all shadow-lg shadow-amber-500/25 disabled:opacity-50 disabled:cursor-not-allowed"
          >
            {isLoading ? (
              <>
                <Loader2 className="w-4 h-4 animate-spin text-slate-950" />
                <span>Verifying...</span>
              </>
            ) : (
              <>
                <span>Confirm Verification</span>
                <ArrowRight className="w-4 h-4 text-slate-950" />
              </>
            )}
          </button>
        </form>

        <div className="pt-4 border-t border-slate-100 dark:border-slate-800 flex items-center justify-between text-xs">
          <button
            type="button"
            onClick={() => {
              setIsRecoveryMode(!isRecoveryMode);
              setCode('');
              setErrorMessage(null);
            }}
            className="text-amber-600 dark:text-amber-400 hover:underline font-semibold"
          >
            {isRecoveryMode ? 'Use Authenticator Code' : 'Use Emergency Recovery Code'}
          </button>
          <button
            type="button"
            onClick={handleCancel}
            className="text-slate-400 hover:text-slate-600 dark:hover:text-slate-200"
          >
            Cancel Login
          </button>
        </div>

        <div className="text-center pt-2">
          <Link
            to="/portal"
            className="text-[11px] text-slate-400 hover:text-amber-500 transition-colors"
          >
            External Customer? Switch to Customer Portal →
          </Link>
        </div>
      </div>
    </div>
  );
};
