import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { ShieldCheck, KeyRound, ArrowRight, Loader2, AlertCircle } from 'lucide-react';
import { useAuth } from '../context/AuthContext.js';

export const MfaChallengePage: React.FC = () => {
  const navigate = useNavigate();
  const { mfaChallenge, verifyMfaLogin, clearMfaChallenge } = useAuth();

  const [code, setCode] = useState('');
  const [isRecoveryMode, setIsRecoveryMode] = useState(false);
  const [isLoading, setIsLoading] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  // If no active challenge, redirect to login
  React.useEffect(() => {
    if (!mfaChallenge) {
      navigate('/login', { replace: true });
    }
  }, [mfaChallenge, navigate]);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setErrorMessage(null);
    setIsLoading(true);

    try {
      await verifyMfaLogin(code.trim(), isRecoveryMode);
      navigate('/', { replace: true });
    } catch (err: any) {
      setErrorMessage(err.message || 'MFA verification failed.');
    } finally {
      setIsLoading(false);
    }
  };

  const handleCancel = () => {
    clearMfaChallenge();
    navigate('/login');
  };

  return (
    <div className="min-h-[calc(100vh-14rem)] flex items-center justify-center py-12 px-4 sm:px-6 lg:px-8">
      <div className="max-w-md w-full space-y-6 bg-card p-8 rounded-xl border shadow-lg">
        <div className="text-center">
          <div className="w-12 h-12 rounded-xl bg-solar-500/10 border border-solar-500/30 flex items-center justify-center text-solar-600 mx-auto mb-4">
            <ShieldCheck className="w-7 h-7 text-solar-500" />
          </div>
          <h2 className="text-2xl font-bold tracking-tight text-foreground">
            Two-Factor Authentication
          </h2>
          <p className="mt-1 text-xs text-muted-foreground">
            {isRecoveryMode
              ? 'Enter an unused 10-character emergency recovery code'
              : 'Enter the 6-digit code generated by your Authenticator app'}
          </p>
        </div>

        {errorMessage && (
          <div className="p-3.5 rounded-lg bg-destructive/10 border border-destructive/20 text-destructive text-xs flex items-start space-x-2">
            <AlertCircle className="w-4 h-4 shrink-0 mt-0.5" />
            <span>{errorMessage}</span>
          </div>
        )}

        <form onSubmit={handleSubmit} className="space-y-4">
          <div>
            <label className="block text-xs font-semibold text-foreground uppercase tracking-wider mb-1.5">
              {isRecoveryMode ? '10-Character Recovery Code' : '6-Digit TOTP Code'}
            </label>
            <div className="relative">
              <div className="absolute inset-y-0 left-0 pl-3 flex items-center pointer-events-none text-muted-foreground">
                <KeyRound className="w-4 h-4" />
              </div>
              <input
                type="text"
                required
                maxLength={isRecoveryMode ? 10 : 6}
                value={code}
                onChange={e => setCode(e.target.value)}
                placeholder={isRecoveryMode ? 'XXXXXXXXXX' : '123456'}
                className="w-full pl-9 pr-3 py-2 text-base font-mono tracking-widest text-center bg-background border rounded-lg focus:outline-none focus:ring-2 focus:ring-solar-500"
              />
            </div>
          </div>

          <button
            type="submit"
            disabled={isLoading || !code}
            className="w-full flex items-center justify-center space-x-2 py-2.5 px-4 rounded-lg bg-solar-600 hover:bg-solar-500 text-white font-medium text-sm transition-all shadow-md shadow-solar-600/20 disabled:opacity-50"
          >
            {isLoading ? (
              <>
                <Loader2 className="w-4 h-4 animate-spin" />
                <span>Verifying...</span>
              </>
            ) : (
              <>
                <span>Confirm Verification</span>
                <ArrowRight className="w-4 h-4" />
              </>
            )}
          </button>
        </form>

        <div className="pt-4 border-t flex items-center justify-between text-xs">
          <button
            type="button"
            onClick={() => {
              setIsRecoveryMode(!isRecoveryMode);
              setCode('');
              setErrorMessage(null);
            }}
            className="text-solar-600 hover:underline font-medium"
          >
            {isRecoveryMode ? 'Use Authenticator Code Instead' : 'Lost Device? Use Recovery Code'}
          </button>
          <button
            type="button"
            onClick={handleCancel}
            className="text-muted-foreground hover:text-foreground"
          >
            Cancel Login
          </button>
        </div>
      </div>
    </div>
  );
};
